"""Generate the midsem report's measurement macros from the artefacts.

Every number that the report states about a MEASUREMENT is defined here, from
the artefact that measured it, and written to `midsem_numbers.tex`.  The report
inputs that file, so a number in the text cannot disagree with the run that
produced it: regenerating the artefacts and re-running this script is the only
way a number changes.

Inputs
    ml_impl/runs/rules/eval_rules.json          rule baselines, N scenes
    ml_impl/runs/<tag>/seed_<s>.json            one record per training seed

Artefact kinds
    an evaluation artefact   has `eval_ck`        -> headline number
    a training artefact      has only `final_ck`  -> the in-training CK, which
                                                    is a curve and not a result

Output
    midsem_numbers.tex      \newcommand definitions, LaTeX-safe
    (printed)               a human-readable summary table, for the log

Run:  python scripts/make_midsem_numbers.py
"""
from __future__ import annotations

import glob
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RUNS = os.path.join(ROOT, "ml_impl", "runs")

#: tag -> (macro stem, human label)
#: The stem decides the macro names: tag "exp_ego_eval" with stem "EgoShape"
#: produces \tokEgoShapeCK, \tokEgoShapeSd, \tokEgoShapeCi, ...
TAGS = {
    "exp_ego_eval": ("EgoShape", "ego bearing + distance shaping, evaluated"),
    "bugfix_eval": ("BugFix", "Part-1 bug fixes alone, held-out protocol"),
    "exp_ego_now_eval": ("EgoShapeNoW", "same, without the W_t penalty"),
    "si_fixed": ("BugFixTrain", "the Part-1 bug fixes alone, training curve"),
    "exp_ego_shape": ("EgoShapeTrain", "same config, training curve only"),
    "exp_ego_shape_now": ("NoWTrain", "W_t removed, training curve only"),
}


def t_half(xs, conf=0.95):
    """Half-width of the t interval on the mean of `xs`."""
    xs = np.asarray(xs, dtype=float)
    n = len(xs)
    if n < 2:
        return float("nan")
    try:
        from scipy import stats
        crit = float(stats.t.ppf(0.5 + conf / 2, n - 1))
    except Exception:                                        # pragma: no cover
        crit = 1.96
    return crit * float(np.std(xs, ddof=1)) / np.sqrt(n)


def load_tag(tag):
    """Per-seed records of one run directory, plus which kind it is."""
    rows = []
    for p in sorted(glob.glob(os.path.join(RUNS, tag, "seed_*.json"))):
        with open(p, encoding="utf-8") as f:
            d = json.load(f)
        d["_path"] = os.path.relpath(p, ROOT)
        rows.append(d)
    if not rows:
        return None
    kind = "eval" if any("eval_ck" in r for r in rows) else "train"
    return {"kind": kind, "rows": rows}


def summarise(rows, kind):
    key = "eval_ck" if kind == "eval" else "final_ck"
    xs = [float(r[key]) for r in rows if r.get(key) is not None]
    if not xs:
        return None
    out = {
        "n": len(xs),
        "mean": float(np.mean(xs)),
        "sd": float(np.std(xs, ddof=1)) if len(xs) > 1 else 0.0,
        "half": t_half(xs),
        "per_seed": xs,
    }
    out["se"] = out["sd"] / np.sqrt(len(xs)) if len(xs) > 1 else 0.0
    return out


def tex(x):
    """A number as LaTeX: three decimals, a leading zero kept, sign kept."""
    return f"{x:.3f}"


def main():
    out = {}
    lines = []
    add = lines.append

    add("% Generated by scripts/make_midsem_numbers.py -- do not edit.")
    add("% Every value is read from an artefact under ml_impl/runs/.")
    add("")

    # ---- rule baselines -------------------------------------------------
    rp = ""
    for cand in ("rules_heldout", "rules"):
        p = os.path.join(RUNS, cand, "eval_rules.json")
        if os.path.exists(p):
            rp = p
            break
    if rp:
        with open(rp, encoding="utf-8") as f:
            rules = json.load(f)
        s = rules.get("summary", {})
        rec = {}
        for name, m in s.items():
            stem = "".join(c for c in name.title() if c.isalnum())
            rec[name] = m
            add(r"\newcommand{\tokRule%sCK}{%s}" % (stem, tex(m["CK"])))
            add(r"\newcommand{\tokRule%sSd}{%s}" % (stem, tex(m["CK_std"])))
        if "Reactive-local" in s:
            add(r"\newcommand{\tokRuleBestName}{the unprivileged reactive rule}")
            add(r"\newcommand{\tokRuleBestCK}{%s}" % tex(s["Reactive-local"]["CK"]))
            add(r"\newcommand{\tokRuleBestSd}{%s}" % tex(s["Reactive-local"]["CK_std"]))
        if "Reactive" in s:
            add(r"\newcommand{\tokRuleReactCK}{%s}" % tex(s["Reactive"]["CK"]))
        add(r"\newcommand{\tokRuleScenes}{%d}" % len(rules.get("eval_seeds", [])))
        add(r"\newcommand{\tokRuleSteps}{%d}" % int(rules.get("steps", 0)))
        # strongest deterministic rule, computed rather than assumed
        best = max(s.items(), key=lambda kv: kv[1]["CK"]) if s else None
        if best:
            add(r"\newcommand{\tokRuleMaxCK}{%s}" % tex(best[1]["CK"]))
            add(r"\newcommand{\tokRuleMaxSd}{%s}" % tex(best[1]["CK_std"]))
        out["rules"] = rec
        add("")

    # ---- trained configurations ----------------------------------------
    for tag, (stem, label) in TAGS.items():
        d = load_tag(tag)
        if d is None:
            continue
        summ = summarise(d["rows"], d["kind"])
        if summ is None:
            continue
        # Prefer the corrected-protocol held-out artefact when it exists:
        # eval_heldout.json evaluates each frozen checkpoint on the same
        # held-out scenes (seeds 1000+), which is the measurement the paper
        # reports.  The seed-json eval_ck may predate that protocol.
        hout = os.path.join(RUNS, tag, "eval_heldout.json")
        if d["kind"] == "eval" and os.path.exists(hout):
            with open(hout, encoding="utf-8") as f:
                h = json.load(f)
            per = [float(v["mean"]) for v in h.get("per_checkpoint", {}).values()]
            if per:
                summ["per_seed"] = per
                summ["n"] = len(per)
                summ["mean"] = float(np.mean(per))
                summ["sd"] = float(np.std(per, ddof=1)) if len(per) > 1 else 0.0
                summ["half"] = t_half(per)
                summ["se"] = summ["sd"] / np.sqrt(len(per)) if len(per) > 1 else 0.0
                det = [float(v["det_mean"]) for v in h.get("per_checkpoint", {}).values()
                       if v.get("det_mean") is not None]
                summ["det"] = float(np.mean(det)) if det else None
                scenes = h.get("eval_seeds", 0)
                summ["scenes"] = int(scenes) if isinstance(scenes, int) else len(scenes)
        out[tag] = {"label": label, "kind": d["kind"], **summ}
        add(r"\newcommand{\tok%sN}{%d}" % (stem, summ["n"]))
        add(r"\newcommand{\tok%sCK}{%s}" % (stem, tex(summ["mean"])))
        add(r"\newcommand{\tok%sSd}{%s}" % (stem, tex(summ["sd"])))
        lo, hi = summ["mean"] - summ["half"], summ["mean"] + summ["half"]
        add(r"\newcommand{\tok%sCi}{[%s, %s]}" % (stem, tex(lo), tex(hi)))
        if d["kind"] == "eval":
            if summ.get("det") is not None:
                add(r"\newcommand{\tok%sDetCK}{%s}" % (stem, tex(summ["det"])))
            elif "det" in summ:
                ds = [float(r["eval_det_ck"]) for r in d["rows"]
                      if r.get("eval_det_ck") is not None]
                if ds:
                    add(r"\newcommand{\tok%sDetCK}{%s}"
                        % (stem, tex(float(np.mean(ds)))))
            if "scenes" in summ:
                add(r"\newcommand{\tok%sScenes}{%d}" % (stem, summ["scenes"]))
            else:
                scenes = d["rows"][0].get("eval_seeds", [])
                add(r"\newcommand{\tok%sScenes}{%d}" % (stem, len(scenes)))
        ep = d["rows"][0].get("episodes")
        if ep:
            add(r"\newcommand{\tok%sEpisodes}{%d}" % (stem, int(ep)))
        add("")

    # ---- the gap to the best rule --------------------------------------
    learner = (out.get("exp_ego_eval") or out.get("exp_ego_now_eval")
               or out.get("exp_ego_shape") or out.get("si_fixed"))
    if learner and "rules" in out:
        best_name = max(out["rules"], key=lambda k: out["rules"][k]["CK"])
        best = out["rules"][best_name]
        gap = best["CK"] - learner["mean"]
        # the rule is deterministic given a scene, so the uncertainty of the
        # difference is the learner's own seed spread; the scenes cancel
        half = learner["half"]
        add(r"\newcommand{\tokNewGap}{%s}" % tex(gap))
        add(r"\newcommand{\tokNewGapCi}{[%s, %s]}" % (tex(gap - half),
                                                     tex(gap + half)))
        add(r"\newcommand{\tokNewGapN}{%d}" % learner["n"])
        add(r"\newcommand{\tokNewGapRule}{%s}" % best_name)
        # the same difference read the other way round, which is the way the
        # corrected section states it: a positive value means the learner is
        # AHEAD of the rule
        add(r"\newcommand{\tokLearnerMinusRule}{%s}" % tex(-gap))
        add(r"\newcommand{\tokLearnerMinusRuleCi}{[%s, %s]}"
            % (tex(-gap - half), tex(-gap + half)))
        out["gap"] = {"to": best_name, "value": gap,
                      "ci": [gap - half, gap + half], "n": learner["n"]}
        # whether the interval excludes zero decides the sentence, so the
        # decision is made here once and the prose reads it
        out["gap"]["learner_ahead_resolved"] = bool(-gap - half > 0)
        out["gap"]["rule_ahead_resolved"] = bool(gap - half > 0)
        if out["gap"]["learner_ahead_resolved"]:
            add(r"\newcommand{\tokGapVerdict}{the learned controller is ahead "
                r"of the strongest rule by an interval that excludes zero}")
        elif out["gap"]["rule_ahead_resolved"]:
            add(r"\newcommand{\tokGapVerdict}{the strongest rule is ahead of "
                r"the learned controller by an interval that excludes zero}")
        else:
            add(r"\newcommand{\tokGapVerdict}{the two are not separated at "
                r"this resolution: the interval on the difference includes "
                r"zero}")

    # ---- diagnostic baselines ------------------------------------------
    rb = os.path.join(RUNS, "diag", "random_baseline.json")
    if os.path.exists(rb):
        with open(rb, encoding="utf-8") as f:
            r = json.load(f)
        per = (r.get("per_seed_CK") or r.get("per_seed") or r.get("cks") or [])
        if per:
            add(r"\newcommand{\tokRandomN}{%d}" % len(per))
            add(r"\newcommand{\tokRandomCK}{%s}" % tex(float(np.mean(per))))
            add(r"\newcommand{\tokRandomSd}{%s}"
                % tex(float(np.std(per, ddof=1)) if len(per) > 1 else 0.0))
            add(r"\newcommand{\tokRandomCi}{[%s, %s]}"
                % (tex(float(np.mean(per)) - t_half(per)),
                   tex(float(np.mean(per)) + t_half(per))))
            out["random"] = {"n": len(per), "mean": float(np.mean(per))}

    path = os.path.join(ROOT, "midsem_numbers.tex")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    # ---- human summary --------------------------------------------------
    print("=" * 78)
    print("MEASUREMENTS  (generated from artefacts; %s)" % path)
    print("=" * 78)
    if "rules" in out:
        print("\nrule baselines over %d scenes, %d steps"
              % (len(rules.get("eval_seeds", [])), int(rules.get("steps", 0))))
        for name, m in sorted(out["rules"].items(), key=lambda kv: kv[1]["CK"]):
            print("  %-18s %.4f  sd %.4f" % (name, m["CK"], m["CK_std"]))
    for tag, (stem, label) in TAGS.items():
        if tag in out:
            s = out[tag]
            print("\n%-18s %-40s %s n=%d" % (tag, label, s["kind"], s["n"]))
            print("  mean %.4f  sd %.4f  95%% CI [%.4f, %.4f]  per-seed %s"
                  % (s["mean"], s["sd"], s["mean"] - s["half"],
                     s["mean"] + s["half"],
                     ", ".join("%.3f" % v for v in s["per_seed"])))
    if "gap" in out:
        g = out["gap"]
        print("\ngap to the strongest rule (%s): %.4f  95%% CI [%.4f, %.4f]"
              % (g["to"], g["value"], g["ci"][0], g["ci"][1]))
    if "random" in out:
        print("random baseline: %.4f over %d seeds"
              % (out["random"]["mean"], out["random"]["n"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
